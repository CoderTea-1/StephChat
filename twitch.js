// GIPHY API INTEGRATION FOR ALT-TEXT GIFS
// ==========================================

function extractGiphySearchTerm(text) {
  if (!text || typeof text !== "string")
    return { searchTerm: null, author: null };
  const match = text.match(/^\[(.*?)\]$/);
  if (!match) return { searchTerm: null, author: null };
  let content = match[1];
  let author = null;

  const byIndex = content.search(/\s+gif\s+by\s+/i);
  if (byIndex !== -1) {
    author = content.substring(byIndex + 8).trim();
    content = content.substring(0, byIndex);
  }

  content = content.replace(/\s+gif$/i, "").trim();

  return { searchTerm: content, author: author };
}

function calculateTokenOverlapScore(
  searchTerm,
  gifTitle,
  targetAuthor,
  itemUser,
) {
  if (!searchTerm || !gifTitle) return 0;
  const searchTokens = searchTerm.toLowerCase().split(/\s+/).filter(Boolean);
  const titleTokens = gifTitle.toLowerCase().split(/\s+/).filter(Boolean);
  if (searchTokens.length === 0 || titleTokens.length === 0) return 0;

  if (targetAuthor && itemUser) {
    const matchesAuthor =
      itemUser.username?.toLowerCase().includes(targetAuthor.toLowerCase()) ||
      itemUser.display_name?.toLowerCase().includes(targetAuthor.toLowerCase());
    if (!matchesAuthor) return -1;
  }

  let matches = 0;
  searchTokens.forEach((token) => {
    if (titleTokens.includes(token)) {
      matches++;
    }
  });

  return matches / searchTokens.length;
}

async function fetchAndRenderGiphyGif(altTextString, container) {
  const { searchTerm, author } = extractGiphySearchTerm(altTextString);
  if (!searchTerm) {
    container.appendChild(document.createTextNode(` ${altTextString}`));
    return;
  }

  let giphyApiKey = "";
  try {
    const res = await fetch("/api/settings");
    if (res.ok) {
      const data = await res.json();
      giphyApiKey = data.settings?.giphyApiKey || "";
    } else {
      await sendDiscordLog(
        "warn",
        `Failed to fetch Giphy settings: API returned status ${res.status}`,
      );
    }
  } catch (err) {
    await sendDiscordLog(
      "error",
      "Failed to fetch Giphy API key from settings",
      err,
    );
  }

  if (!giphyApiKey) {
    container.appendChild(document.createTextNode(` ${altTextString}`));
    return;
  }

  const img = document.createElement("img");
  img.alt = altTextString;
  img.title = altTextString;
  img.className = "chat-gif-embed";
  img.style.maxWidth = "200px";
  img.style.maxHeight = "150px";
  img.style.display = "block";
  img.style.borderRadius = "6px";
  img.style.marginTop = "4px";

  container.appendChild(img);

  try {
    const requestUrl = `https://api.giphy.com/v1/gifs/search?api_key=${encodeURIComponent(giphyApiKey)}&q=${encodeURIComponent(searchTerm)}&limit=5&rating=pg-13`;
    const response = await fetch(requestUrl);
    const json = await response.json();

    if (json.data && json.data.length > 0) {
      let bestGif = json.data[0];
      let bestScore = -1;

      json.data.forEach((item) => {
        const score = calculateTokenOverlapScore(
          searchTerm,
          item.title || "",
          author,
          item.user,
        );
        if (score > bestScore) {
          bestScore = score;
          bestGif = item;
        }
      });

      const imageUrl =
        bestGif.images?.fixed_height?.url ||
        bestGif.images?.original?.url ||
        "";
      if (imageUrl) {
        img.src = imageUrl;
      } else {
        img.remove();
        container.appendChild(document.createTextNode(` ${altTextString}`));
      }
    } else {
      img.remove();
      container.appendChild(document.createTextNode(` ${altTextString}`));
    }
  } catch (e) {
    img.remove();
    container.appendChild(document.createTextNode(` ${altTextString}`));
  }
}

async function renderTwitchEmotes(text, emotesString, container) {
  try {
    const trimmedText = text ? text.trim() : "";

    if (trimmedText.startsWith("[") && trimmedText.endsWith("]")) {
      container.textContent = " ";
      await fetchAndRenderGiphyGif(trimmedText, container);
      return;
    }

    const emoteMap = [];
    const cleanEmotesStr = emotesString
      ? emotesString.replace(/\\:/g, ":").replace(/\\=/g, "=")
      : "";

    cleanEmotesStr.split("/").forEach((emoteGroup) => {
      if (!emoteGroup) return;
      const parts = emoteGroup.split(":");
      if (parts.length < 2) return;
      const id = parts[0];
      parts[1].split(",").forEach((loc) => {
        const range = loc.split("-");
        if (range.length === 2) {
          const start = parseInt(range[0], 10);
          const end = parseInt(range[1], 10);
          if (!isNaN(start) && !isNaN(end)) {
            emoteMap.push({ start, end, id });
          }
        }
      });
    });

    if (emoteMap.length === 0) {
      container.textContent = ` ${text}`;
      return;
    }

    emoteMap.sort((a, b) => a.start - b.start);

    let lastIdx = 0;
    container.textContent = " ";

    emoteMap.forEach((emote) => {
      if (emote.start > lastIdx) {
        container.appendChild(
          document.createTextNode(text.substring(lastIdx, emote.start)),
        );
      }
      const emoteCode = text.substring(emote.start, emote.end + 1);
      const img = document.createElement("img");
      img.src = `https://static-cdn.jtvnw.net/emoticons/v2/${emote.id}/animated/dark/3.0`;
      img.alt = emoteCode;
      img.title = emoteCode;
      img.className = "chat-emote";

      img.onerror = function () {
        this.src = `https://static-cdn.jtvnw.net/emoticons/v2/${emote.id}/static/dark/3.0`;
      };

      container.appendChild(img);
      lastIdx = emote.end + 1;
    });

    if (lastIdx < text.length) {
      container.appendChild(document.createTextNode(text.substring(lastIdx)));
    }
  } catch (e) {
    sendDiscordLog(
      "error",
      "[GiphyDebug] Twitch Emote / Alt-Text Rendering Error:",
      e,
    );
    container.textContent = ` ${text}`;
  }
}

